function top(
  fieldId: string,
  x: number,
  topBaseline: number,
  maxWidth: number,
  fontSize = 7,
  pageIndex = 0,
  required = false,
  markWhen?: string,
  valueTransform?: CoordinatePlacement['valueTransform'],
  markAliases?: readonly string[],
): CoordinatePlacement {
  return {
    kind: 'COORDINATES',
    fieldId,
    required,
    pageIndex,
    x,
    y: PAGE_HEIGHT - topBaseline,
    fontSize,
    maxWidth,
    ...(markWhen === undefined ? {} : { markWhen }),
    ...(valueTransform === undefined ? {} : { valueTransform }),
    ...(markAliases === undefined ? {} : { markAliases }),
  };
}

